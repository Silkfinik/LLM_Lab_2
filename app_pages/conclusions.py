# 2. Сопоставление BLEU/ROUGE и LLM-as-a-Judge
with st.container(border=True):
    st.subheader("2. Сравнение методов оценки качества (BLEU/ROUGE vs LLM-as-a-Judge)", anchor=False)
    st.markdown(
        """
        * **Ограничения n-граммных метрик:** BLEU и ROUGE эффективны **только для детерминированных задач** (извлечение данных 
          по контексту, генерация фиксированных структур JSON, точный перевод). На открытых, креативных и аналитических запросах 
          n-граммные метрики показывают значения около нуля (< 1.0), так как они не способны уловить смысл синонимов и перифраз.
        * **Преимущество LLM-as-a-Judge:** Метод слепого судейства третьей моделью продемонстрировал высокую чувствительность 
          к смысловой логике (например, обнаружение арифметической ошибки в логической задаче №4), грамматической связности и 
          строгости следования системным инструкциям.
        """
    )

# 3. Оценка способа развёртывания
with st.container(border=True):
    st.subheader("3. Оценка способа развёртывания (Локально через Ollama vs Облачные API)", anchor=False)
    st.markdown(
        """
        * **Преимущества локального Ollama:**
          1. **Воспроизводимость и независимость:** Отсутствуют колебания сетевых задержек (ping, jitter), непредвиденные лимиты 
             частоты запросов (Rate Limits) и расходы на токены.
          2. **Прямой доступ к аппаратным ресурсам:** 100% размещение слоев 3B-моделей в 4 ГБ VRAM позволило получить точные 
             аппаратные замеры prefill и decode времени чипа GTX 1650.
          3. **Совместимость с экосистемой OpenAI:** Наличие стандартного REST API (`/v1`) позволило использовать единый код 
             клиента `openai` как для стриминга, так и для судейства.
        * **Ограничение локального подхода:**
          * При объеме видеопамяти 4 ГБ одновременная загрузка двух моделей невозможна. Смена активной модели требует выгрузки 
            и загрузки весов (~1.9–2.0 ГБ за 20–30 секунд), что делает последовательную группировку запросов предпочтительнее попарного чередования.
        """
    )

